#!/usr/bin/env node
/**
 * PreToolUse hook (matcher: Bash) — enforces the git workflow.
 *
 * Rules (see CLAUDE.md → "Git workflow"):
 *  1. Never push, never touch remotes.
 *  2. main: only the very first commit (empty repo). Nothing else, ever.
 *  3. dev: no direct commits; it only receives `git merge --no-ff` from feature branches.
 *  4. Commits happen only on feat|fix|chore|test|docs|perf|refactor/<name> branches.
 *  5. Conventional Commit messages, for commits AND merge commits (type prefix always present).
 *  6. No AI attribution: no Co-Authored-By / Generated-with trailers, no --trailer.
 *  7. Every commit must pass the gate: `pnpm gate` (typecheck + lint + tokens + build).
 *     First commit (no `gate` script yet): `pnpm build` only.
 *  8. One git command per Bash call when committing/merging (no `&&` chains that switch branch).
 *
 * Exit 2 = block the tool call; stderr is shown to Claude.
 */
import { execSync, spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const input = JSON.parse(await readStdin());
const cmd = String(input?.tool_input?.command ?? "");
const cwd = input?.cwd || process.env.CLAUDE_PROJECT_DIR || process.cwd();

if (!/\bgit\b/.test(cmd)) process.exit(0);

const block = (msg) => {
  process.stderr.write(`[guard-git] BLOCKED: ${msg}\n`);
  process.exit(2);
};

const sh = (c) => {
  try {
    return execSync(c, { cwd, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return null;
  }
};

const has = (re) => re.test(cmd);
const isCommit = has(/\bgit\s+commit\b/);
const isMerge = has(/\bgit\s+merge\b/);

// 1. Remotes and history rewriting
if (has(/\bgit\s+push\b/)) block("pushing is forbidden. The user pushes manually.");
if (has(/\bgit\s+remote\s+(add|set-url|remove|rm|rename)\b/)) block("remotes are managed by the user.");
if (has(/\bgit\s+rebase\b/)) block("rebase is forbidden: history must stay as committed.");
if (has(/--no-verify\b/) || has(/\bgit\s+commit\b[^|;&]*\s-n\b/)) block("--no-verify is forbidden.");
if (has(/\bgit\s+commit\b[^|;&]*--amend\b/)) block("--amend is forbidden: make a new small commit instead.");
if (has(/\bgit\s+branch\s+-D\b/)) block("force-deleting branches is forbidden. Use `git branch -d` after merging.");
if (has(/\bgit\s+reset\s+--hard\b/)) block("reset --hard is forbidden.");

if (!isCommit && !isMerge) process.exit(0);

// 6. No AI attribution in commit messages
if (has(/co-authored-by|generated with|generated by|🤖|noreply@anthropic\.com|--trailer\b/i)) {
  block("commit messages must not contain Co-Authored-By / Generated-with trailers or --trailer. Plain Conventional Commit only.");
}

// 8. No branch switching chained with commit/merge
if (has(/(&&|;|\|\|)/) && has(/\bgit\s+(checkout|switch)\b/)) {
  block("run `git switch` and `git commit`/`git merge` as separate Bash calls.");
}

const hasHead = sh("git rev-parse --verify HEAD") !== null;
const branch = hasHead
  ? sh("git rev-parse --abbrev-ref HEAD")
  : sh("git symbolic-ref --short HEAD"); // unborn branch name

// 2. main
if (branch === "main" || branch === "master") {
  if (isMerge) block("never merge into main. The user merges dev → main manually.");
  if (isCommit && hasHead) block("main is frozen after the bootstrap commit. Work on a feature branch from dev.");
  // isCommit && !hasHead → bootstrap commit, allowed (still gated below)
}

// 3. dev
if (branch === "dev") {
  if (isCommit) block("no direct commits on dev. Create a feature branch: /feature-start <name>.");
  if (isMerge && !has(/--no-ff\b/)) block("merges into dev must use `git merge --no-ff <branch>`.");
  if (isMerge && has(/\bgit\s+merge\s+(?:--no-ff\s+)?(?:origin\/)?(main|master)\b/)) block("never merge main into dev.");
}

// 4. Feature branches
const FEATURE = /^(feat|fix|chore|test|docs|perf|refactor)\/[a-z0-9][a-z0-9-]*$/;
if (isCommit && hasHead && branch !== "dev" && branch !== "main" && !FEATURE.test(branch ?? "")) {
  block(`branch "${branch}" is not a valid feature branch (expected e.g. feat/carousel).`);
}
if (isMerge && branch !== "dev") block("merges are only allowed into dev.");

// 5. Conventional Commits (commits and merge commits)
if (isCommit || isMerge) {
  const m = cmd.match(/-m\s+(?:"([^"]*)"|'([^']*)'|\$'([^']*)')/);
  const subject = (m?.[1] ?? m?.[2] ?? m?.[3] ?? "").split(/\\n|\n/)[0];
  if (!m) {
    block(isMerge
      ? 'use `git merge --no-ff <branch> -m "chore(merge): merge <branch> into dev"`.'
      : 'use `git commit -m "<type>(<scope>): <subject>"` (no editor).');
  }
  if ((cmd.match(/\s-m\s/g) || []).length > 1) block("use a single -m (subject line only): no body, no trailers.");
  const CC = /^(feat|fix|chore|docs|test|refactor|style|perf|build|ci)(\([a-z0-9-]+\))?: [a-z].{2,71}$/;
  if (!CC.test(subject)) {
    block(`commit subject "${subject}" is not a Conventional Commit (e.g. "feat(carousel): add pagination dots", lowercase, ≤ 72 chars).`);
  }
}

// 7. Gate — the app must build and render at every commit
if (isCommit) {
  const staged = sh("git diff --cached --name-only");
  if (!staged) block("nothing staged. `git add` the files of this small step first.");
  let hasGate = false;
  try {
    hasGate = Boolean(JSON.parse(readFileSync(join(cwd, "package.json"), "utf8"))?.scripts?.gate);
  } catch {}
  const script = hasGate ? "gate" : "build"; // first commit: bare create-next-app has no gate yet
  const r = spawnSync("pnpm", ["-s", script], { cwd, encoding: "utf8", shell: process.platform === "win32" });
  if (r.status !== 0) {
    const out = `${r.stdout ?? ""}\n${r.stderr ?? ""}`.trim().split("\n").slice(-40).join("\n");
    block(`\`pnpm ${script}\` failed — fix it before committing:\n${out}`);
  }
}

process.exit(0);

function readStdin() {
  return new Promise((resolve) => {
    let data = "";
    process.stdin.setEncoding("utf8");
    process.stdin.on("data", (c) => (data += c));
    process.stdin.on("end", () => resolve(data || "{}"));
  });
}
